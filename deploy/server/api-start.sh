#!/bin/sh
# Старт API на сервере агентства: миграции → справочники → uvicorn.
#
# Миграции — при каждом старте: `alembic upgrade head` на уже свежей базе ничего не делает,
# а выкладка новой версии без миграции — это код, который ждёт схему, которой нет.
# Справочники загружаются тем же `app.seed`, что в облаке: он не трогает правленное
# человеком, только добавляет недостающее.
set -eu

alembic upgrade head
python -m app.seed

# Прокси (Caddy) стоит в той же сети контейнеров: адрес клиента и схему берём из его
# заголовков, иначе журнал видел бы только адрес прокси.
exec uvicorn app.main:app \
    --host 0.0.0.0 \
    --port 8000 \
    --proxy-headers \
    --forwarded-allow-ips '*'
