"""Человекочитаемые номера записей: PRJ-2026-001, TSK-2026-00123.

По ним запись называют вслух и ищут в переписке; идентификатор для этого не годится.

Номер считается по числовому хвосту, а не по строке. На тысячном проекте года строковое
сравнение поставило бы «PRJ-2026-1000» раньше «PRJ-2026-999», номер начал бы повторяться,
а уникальность превратила бы это в отказ заводить новые записи — в декабре, без
объяснения.

Гонка двух созданий закрыта не блокировкой, а уникальностью столбца и повтором:
уникальный индекс не даёт появиться двум записям с одним номером, а `add_with_code`
пересчитывает номер и вставляет заново. Блокировка ради этого стоила бы дороже, чем
случай, который она предотвращает.

Повтор здесь не перестраховка. Столкновение наблюдалось на живом стенде при обычном
вводе подряд: ответ «создано» доходит до клиента раньше, чем закрывается транзакция, и
следующий запрос читает максимум номера, не видя предыдущей записи. Без повтора **каждая
вторая задача, заведённая подряд, пропадала** — с ответом «Внутренняя ошибка» и без
следа в интерфейсе.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from datetime import date
from typing import Any

from sqlalchemy import Integer, cast, func, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.domain.errors import ConflictError

ATTEMPTS = 5
"""Сколько раз пересчитывать номер. Пять — заведомо больше, чем нужно двум вносящим."""


async def next_code(
    session: AsyncSession,
    *,
    column: Any,
    prefix: str,
    digits: int,
    today: date,
) -> str:
    """Следующий свободный номер года для указанного столбца."""
    head = f"{prefix}-{today.year}-"

    last = await session.scalar(
        select(func.max(cast(func.substr(column, len(head) + 1), Integer))).where(
            column.like(f"{head}%")
        )
    )
    return f"{head}{(last or 0) + 1:0{digits}d}"


async def add_with_code(
    session: AsyncSession,
    entity: Any,
    *,
    assign: Callable[[], Awaitable[str]],
    attempts: int = ATTEMPTS,
) -> None:
    """Добавляет запись, пересчитывая номер, пока он не окажется свободным.

    Вставка идёт внутри точки сохранения: при столкновении откатывается она одна, а не
    вся транзакция запроса, — иначе вместе с номером терялось бы всё, что успели сделать
    до него, включая запись в журнал изменений.

    Исчерпание попыток — не «внутренняя ошибка», а состояние, о котором пользователю
    можно сказать словами: номер сейчас занять не удалось, повторите. Пять
    последовательных столкновений при двух вносящих означают, что происходит что-то
    другое, и молчать об этом хуже, чем сказать.
    """
    for _attempt in range(attempts):
        code = await assign()
        try:
            # `add` — внутри точки сохранения, и это не стилистика: запись, добавленная
            # снаружи, принадлежит внешней транзакции, и неудачная вставка помечает
            # откатанной её, а не точку сохранения. Сессия после этого непригодна, и
            # повтор падает уже на попытке взять следующий номер.
            async with session.begin_nested():
                entity.code = code
                session.add(entity)
                await session.flush()
        except IntegrityError as error:
            # Не столкновение по номеру — не наше дело: пробрасываем как есть, иначе
            # ссылка на несуществующего исполнителя пять раз повторится и обернётся
            # сообщением про номер, а настоящую причину придётся искать в журнале.
            if not _is_code_collision(error):
                raise
            continue
        return

    raise ConflictError("Не удалось присвоить номер записи. Повторите попытку.")


def _is_code_collision(error: IntegrityError) -> bool:
    """Столкновение именно по номеру, а не любое нарушение целостности.

    Без этой проверки повтор проглатывал бы, например, ссылку на несуществующего
    исполнителя — пять раз подряд, а затем отвечал бы «не удалось присвоить номер», и
    искать настоящую причину пришлось бы в журнале сервера.
    """
    return "_code" in str(getattr(error.orig, "constraint_name", "") or error.orig)
