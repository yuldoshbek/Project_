"""Порт хранилища файлов.

Содержимое вложений не лежит в базе и не раздаётся приложением: файл кладётся в
S3-совместимое хранилище, а наружу уходит подписанная ссылка с коротким сроком жизни
([ADR-0009](../../../../docs/adr/ADR-0009-attachments.md)). Причина не в экономии: отдавая
файл через себя, приложение держит воркер занятым всё время передачи, и три одновременных
скачивания по пятьдесят мегабайт останавливают систему для обоих пользователей.

Протокол узкий намеренно — положить, прочитать, удалить, выдать ссылку. Всё, что шире
(перечисление бакета, политики, версии объектов), привязало бы нас к S3 так, что заменить
его стало бы невозможно, — а именно ради замены порт и заводится.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import timedelta
from typing import Protocol

from app.settings import Settings


class StorageError(Exception):
    """Хранилище недоступно или отказало.

    Отдельный тип, а не `Exception` из библиотеки: слой выше не должен знать, что внизу
    S3 — иначе замена реализации потребует переписать обработку ошибок везде.
    """


class FileStorage(Protocol):
    """Хранилище содержимого вложений."""

    name: str

    async def put(self, key: str, data: bytes, *, content_type: str) -> None:
        """Кладёт содержимое по ключу. Повторная запись тем же ключом заменяет объект."""
        ...

    async def get(self, key: str) -> bytes:
        """Читает содержимое. Нужно только фоновому преобразованию в PDF."""
        ...

    async def delete(self, keys: Sequence[str]) -> None:
        """Удаляет объекты. Удаление несуществующего ключа — не ошибка."""
        ...

    async def link(
        self,
        key: str,
        *,
        filename: str,
        content_type: str,
        inline: bool,
        lifetime: timedelta,
    ) -> str:
        """Подписанная ссылка на объект.

        `filename` возвращает файлу исходное имя: в хранилище он лежит под ключом вида
        `v2.xlsx`, и без этого пользователь сохранил бы себе на диск файл «v2».

        `inline` различает предпросмотр и скачивание. Это одна и та же ссылка с разным
        заголовком `Content-Disposition`, и разница видна только в браузере: показать в
        окне или предложить сохранить.
        """
        ...


def create_file_storage(settings: Settings) -> FileStorage:
    """Хранилище по настройкам.

    Отдельной строки выбора, как у провайдера личности, здесь нет: реализация одна —
    S3-совместимое хранилище, и MinIO в разработке отличается от него только адресом.
    Подмена в тестах делается не настройкой, а прямой передачей `InMemoryStorage`:
    поднимать ради теста контейнер — значит проверять заодно и сеть.
    """
    from app.adapters.storage.s3 import S3Storage

    return S3Storage(settings)
