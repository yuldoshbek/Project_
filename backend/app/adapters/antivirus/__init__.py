"""Порт антивирусной проверки вложений.

Требование Q7: загруженные файлы проверяются антивирусом. Проверка идёт **до того, как
файл попадает куда бы то ни было** — не в хранилище, не в базу, не в интерфейс. Это
отличается от того, как обычно устраивают такие проверки (сохранить, потом проверить
фоном, потом спрятать заражённое), и отличается намеренно: у файла, который уже лежит и
уже виден, каждая минута до проверки — это минута, когда его может кто-то открыть.

Плата за такой порядок — ожидание в запросе на загрузку. Пятьдесят мегабайт clamd
просматривает секунды, а загружают вложения несколько раз в день, вдвоём.

**Отказ антивируса запрещает загрузку, а не разрешает её.** Недоступный антивирус — это
неизвестно чем закончившаяся проверка, и считать её успешной означает, что достаточно
уронить антивирус, чтобы проверка перестала существовать.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

from app.settings import Settings


class AntivirusUnavailableError(Exception):
    """Антивирус не ответил. Загрузка отклоняется, а не пропускается без проверки."""


@dataclass(frozen=True, slots=True)
class ScanResult:
    """Что антивирус сказал о файле.

    `signature` — имя обнаруженного, когда оно есть. Наружу оно не показывается (по нему
    подбирают то, чего антивирус не знает), но в журнале приложения нужно: без него
    разбор «почему у меня не принимается этот файл» невозможен.
    """

    is_clean: bool
    signature: str | None = None


class VirusScanner(Protocol):
    """Проверяет содержимое до его сохранения."""

    name: str

    async def scan(self, data: bytes) -> ScanResult:
        """Проверяет содержимое. Недоступность поднимает `AntivirusUnavailableError`."""
        ...


def create_virus_scanner(settings: Settings) -> VirusScanner:
    """Антивирус по имени из настроек.

    `disabled` — не проверять. Значение существует ради тестов и разработки без
    поднятого окружения, но доступно и на рабочем контуре: там оно означает, что
    требование СБ не выполняется, и это видно одной строкой в настройках, а не читается
    между строк по отсутствию контейнера.

    Неизвестное имя роняет приложение на старте: опечатка в названии антивируса не должна
    молча означать «проверок нет».
    """
    from app.adapters.antivirus.clamav import ClamAvScanner
    from app.adapters.antivirus.disabled import NoScanner

    if settings.antivirus == "disabled":
        return NoScanner()
    if settings.antivirus == "clamav":
        return ClamAvScanner(settings)
    raise ValueError(
        f"неизвестный антивирус {settings.antivirus!r}; доступны: 'clamav', 'disabled'"
    )
