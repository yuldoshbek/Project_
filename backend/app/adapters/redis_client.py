"""Единая точка создания клиента Redis.

`Redis.from_url` возвращает `Any`, и при `warn_return_any` каждый вызов приходится
подавлять по месту. Нетипизированная граница собрана здесь — один файл, одно подавление,
одно объяснение. Воркер, бот и проверка готовности берут клиента отсюда.
"""

from __future__ import annotations

from redis.asyncio import Redis


def create_redis(url: str) -> Redis:
    """Клиент Redis по строке подключения.

    Вызывающий обязан закрыть его через `aclose()`: незакрытые соединения накапливаются
    в пуле и заканчиваются в самый неподходящий момент.
    """
    return Redis.from_url(url)  # type: ignore[no-any-return]
