"""Порт построения предпросмотра.

ТЗ 6.6 требует смотреть вложения не скачивая. PDF и изображения браузер показывает сам;
для офисных форматов рядом кладётся производный PDF
([ADR-0009](../../../../docs/adr/ADR-0009-attachments.md)).

Преобразование идёт **фоновым заданием, а не в запросе**: это прямое требование ADR-0009,
и причина в том, что LibreOffice открывает тридцатимегабайтную таблицу десятки секунд.
Загрузка, которая столько думает, выглядит как зависшая — человек нажимает «Загрузить»
второй раз, и файлов становится два.

Порт нужен не ради будущей замены LibreOffice, а ради тестов: поднимать контейнер с
офисным пакетом, чтобы проверить, что состояние предпросмотра меняется с «готовится» на
«готов», — значит проверять заодно и сеть, и образ, и шрифты.
"""

from __future__ import annotations

from typing import Protocol

from app.settings import Settings


class ConversionError(Exception):
    """Этот файл преобразовать нельзя: повреждён, зашифрован, неизвестного вида.

    Повторять бессмысленно — через минуту файл не станет другим. Версия получает
    состояние «предпросмотр не построен», и на этом всё.
    """


class ConverterUnavailableError(Exception):
    """Преобразователь недоступен: не отвечает, перегружен, перезапускается.

    Отличается от `ConversionError` не оттенком, а последствием: здесь повторять
    **нужно**. Если не различать эти два случая, то один перезапуск контейнера навсегда
    оставит без предпросмотра все файлы, загруженные в эту минуту, — и никто не узнает,
    потому что выглядеть это будет как «эти файлы не преобразуются».
    """


class DocumentConverter(Protocol):
    """Строит PDF по офисному документу."""

    name: str

    async def to_pdf(self, data: bytes, *, filename: str) -> bytes:
        """Возвращает содержимое PDF.

        `filename` передаётся вместе с содержимым: преобразователь выбирает фильтр по
        расширению. Без имени таблица и презентация выглядят для него одинаково — обе
        просто zip-архивы.
        """
        ...


def create_document_converter(settings: Settings) -> DocumentConverter:
    """Преобразователь по имени из настроек.

    `disabled` — не строить производный PDF вовсе. Тогда офисные вложения остаются без
    предпросмотра и честно показывают это состоянием, а не пустым окном.
    """
    from app.adapters.preview.disabled import NoConverter
    from app.adapters.preview.gotenberg import GotenbergConverter

    if settings.preview_converter == "disabled":
        return NoConverter()
    if settings.preview_converter == "gotenberg":
        return GotenbergConverter(settings)
    raise ValueError(
        f"неизвестный преобразователь {settings.preview_converter!r}; "
        "доступны: 'gotenberg', 'disabled'"
    )
