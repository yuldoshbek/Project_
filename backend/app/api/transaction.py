"""Граница транзакции запроса.

**Транзакция закрывается до того, как ответ уходит клиенту.** Это не оптимизация и не
вкусовщина — без этого система лжёт: она говорит «создано» о записи, которой для
следующего запроса ещё нет.

Так и было. Фиксация жила в разборе зависимости `get_session`, а FastAPI закрывает
зависимости с `yield` **после** отправки ответа. Замерено на стенде 11.09.2026: у двух
последовательных запросов фиксации перекрывались по времени — значит второй запрос ушёл
с клиента раньше, чем первый закрыл свою. Последствия ловились по одному и выглядели как
разные болезни:

- каждая вторая задача, заведённая подряд, пропадала с «Внутренней ошибкой»: номер
  считается как «максимум плюс один», а следующий запрос предыдущей записи не видел;
- отметка пункта чек-листа отвечала «Пункт не найден» для пункта, созданного мгновение
  назад, — три раза из четырёх;
- повторный ввод того же тега другим регистром давал 500 вместо переиспользования.

Первое чинилось повтором, третье чинилось бы повтором, а второе не чинится ничем: нельзя
«повторить» ответ «не найдено» о том, что человек видит на экране.

CLAUDE.md и так помещает транзакции в слой сценариев, а не в доступ к данным. Здесь эта
граница просто становится настоящей: обработчик закончил, ответ собран, но ещё не отдан —
и в этот момент фиксируется транзакция.

Почему не посредник (middleware): посредник оборачивает вызов приложения целиком, и
отправка тела ответа происходит внутри него. Почему не вызов `commit()` в каждом
обработчике: обработчиков десятки, и забыть можно в любом — а забытая фиксация выглядит
как «данные не сохранились через раз». Класс маршрута применяется один раз к роутеру и
действует на все его пути.
"""

from __future__ import annotations

from collections.abc import Callable, Coroutine
from typing import Any

from fastapi import APIRouter, Request, Response
from fastapi.routing import APIRoute
from sqlalchemy.ext.asyncio import AsyncSession

SESSION_STATE_ATTRIBUTE = "session"
"""Имя, под которым сессия запроса лежит в `request.state` (кладёт `deps.get_session`)."""


class CommitOnSuccess(APIRoute):
    """Маршрут, который фиксирует транзакцию до отправки ответа.

    Обработчик, завершившийся исключением, сюда не доходит: исключение уходит выше, к
    обработчикам ошибок, а транзакцию откатывает разбор зависимости. Фиксируется только
    успешный путь — и фиксируется до того, как клиент узнает об успехе.
    """

    def get_route_handler(self) -> Callable[[Request], Coroutine[Any, Any, Response]]:
        handle = super().get_route_handler()

        async def commit_then_answer(request: Request) -> Response:
            response = await handle(request)

            session: AsyncSession | None = getattr(request.state, SESSION_STATE_ATTRIBUTE, None)
            if session is not None:
                await session.commit()

            return response

        return commit_then_answer


def transactional_router(**kwargs: Any) -> APIRouter:
    """Роутер, у которого граница транзакции на месте.

    Все роутеры API создаются через него, а не через `APIRouter` напрямую: роутер,
    заведённый мимо, тихо возвращается к прежнему поведению — работает, но обещает
    записанное раньше, чем оно записано. Соблюдение проверяется тестом (`test_conventions`).
    """
    return APIRouter(route_class=CommitOnSuccess, **kwargs)
