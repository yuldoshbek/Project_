"""Который сегодня день — и в каком часовом поясе.

Хранение везде в UTC, показ и все календарные решения — в `Asia/Tashkent` (CLAUDE.md,
инвариант о времени). Разница не абстрактная: в два часа ночи по Ташкенту в UTC ещё
вчерашний день, и проект со вчерашним сроком выглядел бы не просроченным. Ошибка
проявляется ночью, у одного пользователя из двух, и в отчёте её не видно.

Поэтому «сегодня» — не окружающий факт, а входное значение: функции, которым оно нужно,
требуют его явно, а не берут из системных часов.
"""

from __future__ import annotations

from datetime import UTC, date, datetime
from zoneinfo import ZoneInfo


def today_in(timezone: str) -> date:
    """Календарная дата в указанном поясе.

    `datetime.date.today()` здесь не годится: он берёт пояс машины, а машина стоит там,
    где её развернули, — это не тот пояс, в котором наступают сроки агентства.
    """
    return datetime.now(UTC).astimezone(ZoneInfo(timezone)).date()


def local_date(moment: datetime, zone: ZoneInfo) -> date:
    """Календарная дата момента в поясе пользователей.

    `moment.date()` здесь не годится: у времени из базы пояс UTC, и срок «26.09 в 03:00
    по Ташкенту» — это «25.09 в 22:00» по UTC. Взятая так дата делает работу просроченной
    на сутки раньше, и заметно это только ночью.
    """
    if moment.tzinfo is None:
        # Время без пояса в системе не хранится (инвариант 8). Появилось — это ошибка в
        # коде, а не в данных, и угадывать пояс молча значило бы спрятать её.
        raise ValueError("момент без часового пояса: хранение только timestamptz")
    return moment.astimezone(zone).date()


def now_utc() -> datetime:
    """Текущий момент в UTC.

    Отдельная функция по той же причине, что и `today_in`: время — такой же вход, как
    «сегодня». В тестах подставляется момент, а не подкручиваются часы машины.
    """
    return datetime.now(UTC)
