"""Чек-листы задач: что хранится и что вычисляется.

**Прогресс чек-листа не хранится.** Он считается на выдаче из самих пунктов — по той же
причине, по которой не хранится просрочка (инвариант 1): хранимое число расходится с тем,
из чего оно посчитано, и расходится молча. Пункт удалили напрямую в базе, привоз добавил
пять штук, откатилась транзакция на середине — и счётчик показывает «3 из 5» там, где
пунктов четыре. Спорить с ним нечем: он и есть источник.

**Пустой чек-лист не имеет прогресса.** Не ноль процентов и не сто: задача без чек-листа —
это не «задача, в которой ничего не сделано». Разница видна на экране списка, где ноль
процентов читается как тревога, а отсутствие чек-листа не значит ничего.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.domain.errors import RuleViolationError

ITEM_MAX_LENGTH = 500
"""Пункт чек-листа — одно действие. Длиннее — это уже описание задачи."""


@dataclass(frozen=True, slots=True)
class ChecklistProgress:
    """Сколько пунктов выполнено из скольких. Считается, не хранится."""

    done: int
    total: int

    @property
    def percent(self) -> int | None:
        """Доля выполненного или `None`, когда чек-листа нет.

        `None`, а не ноль: ноль означает «взялись и не сделали», и на экране это
        тревожный знак. Задача без чек-листа не сообщает о себе ничего такого.

        Округление вниз намеренно: «99 %» при одном невыполненном пункте из ста честнее,
        чем «100 %» у незавершённого дела. Стоило бы округлять к ближайшему — и последний
        пункт перестал бы быть виден.
        """
        if self.total == 0:
            return None
        return self.done * 100 // self.total


def progress(*, done: int, total: int) -> ChecklistProgress:
    if done < 0 or total < 0:
        raise ValueError("отрицательное число пунктов чек-листа")
    if done > total:
        raise ValueError("выполненных пунктов больше, чем всего")
    return ChecklistProgress(done=done, total=total)


def clean_item(text: str) -> str:
    """Текст пункта: без пробелов по краям, непустой, без нулевого символа."""
    if "\x00" in text:
        raise RuleViolationError("В пункте чек-листа есть недопустимый символ")
    value = text.strip()
    if not value:
        raise RuleViolationError("Напишите, что нужно сделать")
    if len(value) > ITEM_MAX_LENGTH:
        raise RuleViolationError(f"Пункт длиннее {ITEM_MAX_LENGTH} символов")
    return value
