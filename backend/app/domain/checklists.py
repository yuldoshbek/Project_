"""Чек-листы и теги задач: что хранится и что вычисляется.

**Прогресс чек-листа не хранится.** Он считается на выдаче из самих пунктов — по той же
причине, по которой не хранится просрочка задачи
([ADR-0004](../../../docs/adr/ADR-0004-overdue-is-computed.md)) и «пропущенность» вехи:
хранимое число расходится с тем, из чего оно посчитано, и расходится молча. Пункт удалили
напрямую в базе, импорт добавил пять штук, откатилась транзакция на середине — и счётчик
показывает «3 из 5» там, где пунктов четыре. Спорить с ним нечем: он и есть источник.

**Пустой чек-лист не имеет прогресса.** Не ноль процентов и не сто: задача без чек-листа —
это не «задача, в которой ничего не сделано». Разница видна на экране списка, где ноль
процентов читается как тревога, а отсутствие чек-листа не значит ничего.

**Тег — общий словарь, а не свойство задачи.** Он существует затем, чтобы по нему собрать
задачи из разных проектов; «ДЗЗ», «дзз» и «ДЗЗ » — один тег, и три записи вместо одной
разрушают ровно то, ради чего теги заводились (ТЗ 6.2).
"""

from __future__ import annotations

import re
from dataclasses import dataclass

TAG_MAX_LENGTH = 50

_SPACES = re.compile(r"\s+")


@dataclass(frozen=True, slots=True)
class ChecklistProgress:
    """Сколько пунктов выполнено из скольких. Считается, не хранится."""

    done: int
    total: int

    @property
    def percent(self) -> int | None:
        """Доля выполненного или `None`, когда чек-листа нет.

        `None`, а не ноль: ноль означает «взялись и не сделали», и на экране это
        тревожный знак. Задача без чек-листа не сообщает о себе ничего такого.

        Округление вниз намеренно: «99 %» при одном невыполненном пункте из ста честнее,
        чем «100 %» у незавершённого дела. Стоило бы округлять к ближайшему — и последний
        пункт перестал бы быть виден.
        """
        if self.total == 0:
            return None
        return self.done * 100 // self.total


def progress(*, done: int, total: int) -> ChecklistProgress:
    if done < 0 or total < 0:
        raise ValueError("отрицательное число пунктов чек-листа")
    if done > total:
        raise ValueError("выполненных пунктов больше, чем всего")
    return ChecklistProgress(done=done, total=total)


def normalize_tag(name: str) -> str:
    """Написание тега, по которому он узнаётся.

    Схлопываются пробелы по краям и внутри: «ДЗЗ  Ташкент» и «ДЗЗ Ташкент» — один тег, а
    различие между ними на экране неразличимо. Регистр **не** трогается: он остаётся
    таким, каким тег завели, а совпадение без учёта регистра обеспечивает тип столбца
    (`citext`). Приведи здесь к нижнему — и «ДЗЗ» навсегда стало бы «дзз».
    """
    cleaned = _SPACES.sub(" ", name).strip()
    if not cleaned:
        raise ValueError("пустой тег")
    if len(cleaned) > TAG_MAX_LENGTH:
        raise ValueError(f"тег длиннее {TAG_MAX_LENGTH} знаков")
    return cleaned
