"""Коды справочников, от которых зависит поведение системы.

Здесь разрешается противоречие, заложенное в ТЗ. Раздел 3.9 требует, чтобы справочники
редактировал помощник, а не разработчик; раздел 4 требует, чтобы система понимала смысл
значений — считала просрочку и лестницу внимания. Полностью редактируемый справочник
этого не позволяет: смысл нового значения системе неоткуда взять.

Разделение такое:

- **код принадлежит коду** — перечисления ниже, на них опирается логика;
- **название, порядок, цвет и видимость принадлежат данным** — таблицы справочников,
  помощник меняет их в интерфейсе.

Практическое следствие: переименовать «На паузе» можно из интерфейса и на всех трёх
письменностях; завести пятый статус проекта — нельзя, потому что системе неоткуда узнать,
что он означает.

Типы проектов и типы задач сюда **не попадают**: у них смысл не нужен коду. Тип проекта
приносит шаблон вех, тип задачи — только название; и то и другое целиком принадлежит
данным (ТЗ 3.9) и живёт таблицами.
"""

from __future__ import annotations

from enum import StrEnum


class ProjectStatus(StrEnum):
    """Статусы проекта (ТЗ 3.1). Их ровно четыре.

    «Просрочен» и «ждёт решения» здесь отсутствуют, и это не упущение: первое —
    вычисляемое состояние (инвариант 1), второе — ступень лестницы внимания
    (`app.domain.attention`). Записав их статусом, мы потеряли бы ответ на вопрос, идёт
    работа или стоит.
    """

    IN_PROGRESS = "in_progress"
    ON_HOLD = "on_hold"
    DONE = "done"
    CANCELLED = "cancelled"

    @property
    def is_terminal(self) -> bool:
        """Работа закончена: в сигналы такой проект не попадает."""
        return self in {ProjectStatus.DONE, ProjectStatus.CANCELLED}

    @property
    def requires_reason(self) -> bool:
        """Пауза и отмена требуют причины: она же потом снимает паузу."""
        return self in {ProjectStatus.ON_HOLD, ProjectStatus.CANCELLED}


class TaskStatus(StrEnum):
    """Статусы задачи (ТЗ 3.2).

    «Просрочена» отсутствует по той же причине, что и у проекта. В интерфейсе
    пользователь её видит — как признак и как значение фильтра.
    """

    NEW = "new"
    IN_PROGRESS = "in_progress"
    IN_REVIEW = "in_review"
    DONE = "done"
    CANCELLED = "cancelled"

    @property
    def is_terminal(self) -> bool:
        return self in {TaskStatus.DONE, TaskStatus.CANCELLED}


class OrganizationKind(StrEnum):
    """Вид организации (ТЗ 3.4).

    Хокимият вынесен отдельно от ведомства: ТЗ 3.1 просит срез по регионам, а он
    собирается именно по хокимиятам — четырнадцать областей и город.
    """

    MINISTRY = "ministry"
    AGENCY = "agency"
    KHOKIMIYAT = "khokimiyat"
    INTERNATIONAL = "international"
    COMPANY = "company"


class OrganizationRole(StrEnum):
    """Кем организация приходится проекту (ТЗ 3.1, CONTEXT «Роль организации»).

    Набор закрытый, потому что на нём держится расчёт: «зависит от чужих» — это
    головное ведомство не наше (`app.domain.attention`). Свободная строка в этом месте
    означала бы, что сигнал считается по написанию.
    """

    CUSTOMER = "customer"
    EXECUTOR = "executor"
    CO_EXECUTOR = "co_executor"
    LEAD_AGENCY = "lead_agency"


class SettingKey(StrEnum):
    """Пороги сигналов (ТЗ 4). Значения живут в таблице и меняются без выкладки.

    Здесь только то, что нужно блоку 1. Пороги писем и соглашений приезжают вместе с
    разделом «Взаимодействие» своей миграцией: порог без показателя, который его читает,
    — это настройка, которую некому объяснить (инвариант 14).
    """

    BURN_DAYS = "burn_days"
    """За сколько дней до срока работа считается горящей. По умолчанию 7 (ТЗ 4)."""

    QUIET_DAYS = "quiet_days"
    """Сколько дней без движения считается молчанием. По умолчанию 14 (ТЗ 4)."""

    IMPEDIMENT_STALE_DAYS = "impediment_stale_days"
    """Через сколько дней строка «что мешает» перестаёт считаться действующей."""

    MIN_CLOSED_FOR_PACE = "min_closed_for_pace"
    """Сколько задач надо закрыть, чтобы отвечать на «успеваем?». Меньше — «мало данных»."""

    SUMMARY_AT = "summary_at"
    """Время утренней сводки по Ташкенту (ТЗ 8)."""
