"""Решения руководителя (ТЗ 3.7).

Ради этого система и существует: она показывает, что требует внимания, а руководитель
одним касанием отвечает — утвердить, вернуть, поручить, поторопить, эскалировать, просить
продление, отклонить. Каждое решение попадает в журнал решений, и по нему видно,
выполнено оно или нет.

**Решение — единственное, что руководитель записывает сам.** Всё остальное вносит
помощник ([ADR-0011](../../../docs/adr/ADR-0011-two-user-scope.md)), и это исключение
проверяется в коде явно, а не послаблением общего охранника.

Состояние здесь — «открыто» и «выполнено», хотя ТЗ 3.7 перечисляет три и называет третьим
«просрочено». Третье — вычисляемое (инвариант 1): срок исполнения прошёл, а решение не
закрыто. Записав его состоянием, мы потеряли бы ответ на вопрос, взялся ли кто-нибудь за
исполнение.
"""

from __future__ import annotations

from datetime import date
from enum import StrEnum

TEXT_MAX_LENGTH = 1000
"""Решение — это указание, а не докладная записка.

Ограничение не техническое: поле, куда помещается страница, через месяц содержит
страницу, и читать его перестают — вместе со всем остальным.
"""


class DecisionKind(StrEnum):
    """Вид решения (ТЗ 3.7). Набор закрытый: у каждого вида своё следствие на экране."""

    APPROVE = "approve"
    RETURN = "return"
    ASSIGN = "assign"
    HURRY = "hurry"
    ESCALATE = "escalate"
    ASK_EXTENSION = "ask_extension"
    REJECT = "reject"

    @property
    def closes_the_question(self) -> bool:
        """Снимает ли решение вопрос к руководителю.

        «Утвердить», «отклонить» и «вернуть» — ответ: объект уходит со ступени «ждёт
        решения» немедленно. «Поручить», «поторопить», «эскалировать» и «просить
        продление» — тоже ответ, но они ставят срок кому-то другому, и объект ждёт уже
        не руководителя, а исполнения.
        """
        return self in {DecisionKind.APPROVE, DecisionKind.REJECT, DecisionKind.RETURN}

    @property
    def needs_assignee(self) -> bool:
        """Поручение без ответственного — это не поручение, а пожелание."""
        return self in {DecisionKind.ASSIGN, DecisionKind.HURRY, DecisionKind.ESCALATE}


class DecisionState(StrEnum):
    """То, что хранится. «Просрочено» вычисляется (инвариант 1)."""

    OPEN = "open"
    DONE = "done"

    @property
    def is_terminal(self) -> bool:
        return self is DecisionState.DONE


class DecisionTarget(StrEnum):
    """По чему принимается решение.

    Закрытый набор, а не свободная строка: по значению собирается обратная ссылка на
    карточку, и третье написание того же слова («task» и «tasks») развалило бы журнал
    решений, не сломав ни одного запроса.
    """

    PROJECT = "project"
    TASK = "task"
    MILESTONE = "milestone"
    IJRO_ASSIGNMENT = "ijro_assignment"


def is_overdue(*, due_on: date | None, state: DecisionState, today: date) -> bool:
    """Просрочено ли исполнение решения.

    Решение без срока не бывает просроченным: срок, которого не назначали, не наступает.
    Руководитель вправе сказать «поторопить» без даты — это всё ещё решение.
    """
    if due_on is None or state.is_terminal:
        return False
    return due_on < today
