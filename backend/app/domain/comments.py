"""Лента хода исполнения поручения «Ижро» (ТЗ 3.3).

**Одна лента и один владелец.** У проекта и задачи ленты нет: ТЗ v2.0 их не предусматривает,
и обсуждение работы живёт там же, где оно и жило всегда, — в разговоре. У поручения иначе:
состояние из связанных задач не выводится (ТЗ 3.3), и ответ на вопрос руководителя «что мы
сделали по этому поручению» собирается из отметок, реплик и вложений. Без ленты этот
вопрос остаётся без ответа.

**Реплика не удаляется насовсем.** Ход исполнения — это последовательность событий, а не
черновик: удалённая реплика уносит с собой смысл соседних, и через месяц лента читается
как разговор с пропусками. Поэтому удаление мягкое, а на месте реплики остаётся след
«комментарий удалён» — без текста, но с автором и временем.
"""

from __future__ import annotations

from enum import StrEnum

BODY_MAX_LENGTH = 5000


class CommentTarget(StrEnum):
    """К чему относится реплика.

    Одно значение, а не свободная строка, и таблица при этом с полиморфной ссылкой: в
    блоке 2 к поручению добавится письмо и подготовка доклада, и вторая таблица под ту же
    ленту однажды разошлась бы с первой по поведению — чинить пришлось бы обе.
    """

    IJRO_ASSIGNMENT = "ijro_assignment"


def validate_body(body: str) -> str:
    """Текст реплики, пригодный к сохранению.

    Пустая реплика отклоняется: она ничего не сообщает, но занимает место в ленте и
    сбивает счёт событий. Пробелы по краям срезаются — иначе «  » пройдёт проверку на
    непустоту.
    """
    cleaned = body.strip()
    if not cleaned:
        raise ValueError("пустой комментарий")
    if len(cleaned) > BODY_MAX_LENGTH:
        raise ValueError(f"комментарий длиннее {BODY_MAX_LENGTH} знаков")
    return cleaned
