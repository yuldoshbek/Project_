"""Комментарии: что это такое и как разбираются упоминания.

**Комментарий не удаляется насовсем.** Обсуждение — это ход событий, а не черновик:
удалённая реплика уносит с собой смысл соседних, и через месяц переписка читается как
разговор с пропусками. Поэтому удаление мягкое, а в ленте на месте реплики остаётся след
«комментарий удалён» — без текста, но с автором и временем. Иначе мягкое удаление
бессмысленно: оно и заводится ради того, чтобы след остался.

**Упоминание разбирается при сохранении, а не при показе.** Разбор на показе означал бы,
что смысл старой реплики меняется вместе со справочником сотрудников: уволился человек —
и упоминание перестало быть упоминанием. Здесь наоборот: что разобрали при сохранении, то
и осталось.
"""

from __future__ import annotations

import re
from enum import StrEnum

BODY_MAX_LENGTH = 5000

MENTION = re.compile(r"@([^\s@,;:!?()\[\]{}«»\"']{2,50})")
"""Упоминание — «собака» и слово без пробелов (SPEC 1.5).

Знаки препинания в имя не входят: «@Рахимов,» — это упоминание Рахимова и запятая, а не
человек с запятой в фамилии. Две буквы минимум: «@я» — это не обращение, а опечатка.
"""


class CommentTarget(StrEnum):
    """К чему относится комментарий.

    Два значения, а не свободная строка: `entity_type` — часть ключа поиска, и третье
    написание того же слова («task» и «tasks») развалит ленту, не сломав ни одного запроса.
    """

    PROJECT = "project"
    TASK = "task"


def validate_body(body: str) -> str:
    """Текст комментария, пригодный к сохранению.

    Пустой комментарий отклоняется: он ничего не сообщает, но занимает место в ленте и
    сбивает счёт реплик. Пробелы по краям срезаются — иначе «  » пройдёт проверку на
    непустоту.
    """
    cleaned = body.strip()
    if not cleaned:
        raise ValueError("пустой комментарий")
    if len(cleaned) > BODY_MAX_LENGTH:
        raise ValueError(f"комментарий длиннее {BODY_MAX_LENGTH} знаков")
    return cleaned


def find_mentions(body: str) -> list[str]:
    """Слова после «собаки», в порядке появления и без повторов.

    Порядок сохраняется намеренно: по нему потом видно, кого упомянули первым, — а это
    обычно тот, к кому обращаются. Повтор одного и того же имени в одной реплике — это
    одно упоминание, а не два: человека не извещают дважды за один текст.
    """
    seen: dict[str, None] = {}
    for match in MENTION.finditer(body):
        seen.setdefault(match.group(1), None)
    return list(seen)
