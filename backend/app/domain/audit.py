"""Журнал изменений: что записывается и что из записи видно.

Журнал отвечает на вопрос «кто и когда это изменил», а не хранит копию данных. Поэтому
в записи лежат **только изменившиеся поля** в форме `{"поле": {"from": …, "to": …}}`:
снимок целиком раздувает журнал и утекает лишними данными
([ADR-0010](../../../docs/adr/ADR-0010-audit-log.md)).

Здесь только правила. Как достать изменения из сессии — в `app.services.audit`: домен не
знает про SQLAlchemy (CLAUDE.md, границы слоёв).
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any

MASK = "***"
"""Чем заменяются значения полей закрытой записи.

Заменяются значения, а не факт изменения: журнал обязан показывать, что запись трогали,
даже когда содержимое наружу не выдаётся
([ADR-0007](../../../docs/adr/ADR-0007-restricted-data.md)). Иначе закрытый проект можно
менять бесследно — а это ровно та дыра, от которой журнал должен защищать.
"""


class AuditAction(StrEnum):
    """Что произошло с записью."""

    CREATED = "created"
    UPDATED = "updated"
    DELETED = "deleted"

    DOWNLOADED = "downloaded"
    """Выдана ссылка на файл проекта с грифом (ADR-0009).

    Единственное действие в этом перечне, которое ничего не меняет. Записывается потому,
    что ссылка на файл — это доступ к содержимому в обход входа в систему: она действует
    сама по себе, пока не истечёт. Для закрытых проектов вопрос «кто и когда выносил это
    наружу» должен иметь ответ, а изменением такое действие не является — значит, сам
    журнал изменений его не заметит.

    Обычные загрузки так не записываются: журнал, в который попадает каждое открытие
    каждого вложения, перестаёт читаться, а вместе с ним перестают замечаться и те
    записи, ради которых он заводился.
    """


class ActorKind(StrEnum):
    """Кто изменил.

    Различать обязательно: без этого эскалация по сроку и автосоздание повторяющейся
    задачи выглядят в журнале как действия непонятно кого, и первый же разбор
    «кто поменял срок» упирается в тупик (ADR-0010).
    """

    HUMAN = "human"
    """Помощник или руководитель через интерфейс либо бота."""

    JOB = "job"
    """Фоновое задание: напоминание, эскалация, повтор, снимок состояния."""

    INTEGRATION = "integration"
    """Внешняя система: обмен с SETA, Google-календарь."""


Changes = dict[str, dict[str, Any]]


def mask_changes(changes: Changes) -> Changes:
    """Прячет значения, оставляя имена полей и сам факт изменения."""
    return {field: dict.fromkeys(sides, MASK) for field, sides in changes.items()}
