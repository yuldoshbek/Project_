"""Ошибки предметной области.

Домен не знает ни про HTTP, ни про FastAPI (CLAUDE.md, границы слоёв): здесь описано
**что случилось**, а не каким кодом это отдать. Сопоставление с кодами ответа живёт в
`app.api.errors` — единственном месте, где домен встречается с протоколом.
"""

from __future__ import annotations


class DomainError(Exception):
    """Базовая ошибка предметной области.

    `code` попадает в поле `type` ответа и остаётся стабильным: интерфейс и бот
    опираются на него, а не на текст сообщения, который меняется вместе с переводом.
    """

    code: str = "domain-error"

    def __init__(self, message: str, *, detail: str | None = None) -> None:
        super().__init__(message)
        self.message = message
        self.detail = detail


class NotFoundError(DomainError):
    """Записи нет либо она недоступна обратившемуся.

    Оба случая отвечают одинаково: сообщение «нет доступа» подтверждает, что запись
    существует, — этого достаточно, чтобы по перебору идентификаторов узнать состав
    портфеля.
    """

    code = "not-found"


class ConflictError(DomainError):
    """Действие противоречит текущему состоянию записи.

    Например, попытка перевести задачу из «выполнена» в «новая» минуя «в работе»
    (ADR-0004) или загрузка файла, который уже есть в этой версии.
    """

    code = "conflict"


class RuleViolationError(DomainError):
    """Нарушено правило предметной области.

    Отличается от ошибки формата запроса: данные корректны, но не годятся по смыслу —
    срок завершения раньше даты начала, статус «Приостановлен» без указания причины.
    """

    code = "rule-violation"


class PermissionDeniedError(DomainError):
    """Роль не позволяет выполнить действие.

    Применяется там, где запись заведомо известна обратившемуся, но менять её он не
    вправе: руководитель видит проект, но изменить может только решение по нему
    (ADR-0011). Когда сам факт существования записи скрывается — это `NotFoundError`.
    """

    code = "permission-denied"


class ExternalServiceError(DomainError):
    """Внешняя система недоступна или ответила отказом.

    Google-календарь и Telegram отказывают регулярно, и это не ошибка пользователя:
    ответ должен объяснять, что данные могли устареть, а не выглядеть поломкой системы.
    """

    code = "external-service-unavailable"
