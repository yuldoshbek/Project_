_DOCUMENT_NOISE = re.compile(r"[«»\"'`.,;:()\[\]/\\]+")
"""Знаки, которые в номере ничего не значат.

Косая черта здесь потому, что ячейка документа приходит тремя абзацами, и склеивать их
можно по-разному. Ключ не должен зависеть от того, чем их соединили.
"""

_DOCUMENT_KIND_WORD = re.compile(
    r"(фармон|карор|конун|баён|баен|топширик|хужжат)",
    re.IGNORECASE,
)
"""Вид документа в ключ не входит.

В источнике он то есть, то нет: «Қарор ВМҚ-135 31.03.2026» и «ВМҚ-135 31.03. 2026» — один
документ, записанный дважды. Опознаёт документ номер, а вид — подпись к нему, и ставить
её в ключ значит развести одну запись на две.

Формы записаны после складывания узбекских букв (`қ` → `к`, `ҳ` → `х`), потому что к
этому моменту текст уже сложен: искать здесь «қарор» значило бы искать то, чего в строке
уже нет.
"""

_DOCUMENT_TAIL = re.compile(r"(сонли|сон|йилдаги|йил|й)(?=\d|\b|$)", re.IGNORECASE)
"""Служебные хвосты. Без границы слова слева намеренно.

`\\b` их не ловит: в данных встречается «ПҚ-99-сон13.03.2026й» — весь номер одной строкой,
и ни перед «сон», ни перед «й» границы слова нет. Правило, требующее пробела, сработало бы
на аккуратных написаниях и промолчало на слипшихся, то есть ровно там, где нужно.
"""


def normalize_document_code(value: str) -> str:
    """Ключ склейки написаний одного документа.

    В источнике ПФ-155 записан двумя способами — «Фармон ПФ-155-сон 14.10.2024 й» и
    «Фармон ПФ-155 14.10.2024», — и встречается 32 раза. Без склейки вопрос «что мы
    сделали по ПФ-155» получил бы ответ по 23 строкам вместо 32 и не подал бы виду.

    Что убирается: служебные хвосты (`-сон`, `й`, `йил`), знаки препинания, пробелы,
    регистр, латинские омоглифы. Что **остаётся** — всё прочее, как есть: 12 ячеек из 165
    не содержат узнаваемого вида документа вовсе (`02-1671xdfu`, `78`, `19-2632`), и белый
    список видов потерял бы 8 % реестра. Запасной путь здесь не исключение, а норма.
    """
    text = normalize_spaces(value).translate(_HOMOGLYPHS).translate(_UZBEK_FOLD).lower()
    text = _DOCUMENT_NOISE.sub(" ", text)
    text = _DOCUMENT_KIND_WORD.sub(" ", text)
    text = _DOCUMENT_TAIL.sub(" ", text)
    return re.sub(r"[\s-]+", "", text)


