_SPACES = re.compile(r"[\s\u00a0\u2000-\u200b\u202f\u2060]+")
"""Пробельные знаки, включая неразрывный.

Неразрывный пробел здесь не редкость: в данных он встречается прямо в обозначении пункта
(`3.3.\u00a0Белгилансинки`). Обычное `str.split()` его не видит, и написание, отличающееся
только им, превратилось бы во второго человека или второй документ.
"""


def normalize_spaces(value: str) -> str:
    """Схлопывает любые пробелы в один и обрезает края."""
    return _SPACES.sub(" ", value).strip()


_HOMOGLYPHS = str.maketrans(
    {
        "X": "Х",
        "K": "К",
        "O": "О",
        "P": "Р",
        "A": "А",
        "B": "В",
        "C": "С",
        "E": "Е",
        "H": "Н",
        "M": "М",
        "T": "Т",
        "Y": "У",
        "x": "х",
        "k": "к",
        "o": "о",
        "p": "р",
        "a": "а",
        "b": "в",
        "c": "с",
        "e": "е",
        "h": "н",
        "m": "м",
        "t": "т",
        "y": "у",
    }
)
"""Латинские буквы, неотличимые от кириллических на вид.

В данных это не гипотеза: `X. Рахмонов` написан латинской X четыре раза, `Х. Рахмонов`
кириллической — семь. Глазами это один человек, программой — два, и показатель загрузки
разъезжается молча.
"""

_UZBEK_FOLD = str.maketrans(
    {"Қ": "К", "қ": "к", "Ғ": "Г", "ғ": "г", "Ҳ": "Х", "ҳ": "х", "Ў": "У", "ў": "у"}
)
"""Узбекские буквы, сводимые к базовым **только в ключе сравнения**.

`Қ. Эрматов` и `K. Эрматов` — один человек: латинская K превращается в К, а К и Қ в
инициалах пишут как придётся. То же с Ҳ/Х и Ў/У.

Складывание применяется к ключу, а не к тексту: исходное написание всегда остаётся в
`responsible_raw`, и показать человека можно так, как его записал источник.
"""


def normalize_person_name(value: str) -> str:
    """Ключ сравнения написаний ФИО.

    Что делается: схлопываются пробелы, латинские омоглифы заменяются кириллицей,
    узбекские буквы складываются к базовым, `И.Фамилия` разводится в `И. Фамилия`,
    регистр приводится к нижнему.

    **Чего не делается — важнее.** Не склеиваются `Арибжанов` и `Арибжонов`: узбекская
    вариативность «а/о» в фамилиях настоящая, и правило, сводящее их, однажды сведёт двух
    разных людей. Не отбрасывается инициал: `Ш. Арибжанов` и `А. Арибжанов` — разные
    люди, и в данных они оба есть. Всё, что сложнее механической разницы, подтверждает
    человек ([ADR-0025](../../../docs/adr/ADR-0025-ijro-standalone-register.md)).
    """
    text = normalize_spaces(value).translate(_HOMOGLYPHS).translate(_UZBEK_FOLD)
    # «И.Фамилия» → «И. Фамилия»: точка сразу за одной буквой — это инициал без пробела.
    text = re.sub(r"(?<=\b\w)\.(?=\w)", ". ", text)
    return normalize_spaces(text).lower()


LEAD_EXECUTOR_MARKER = "асосий ижрочи"
"""Маркер головного исполнителя.

Ищется вхождением, а не по абзацам: в данных он стоит и отдельной строкой ячейки
(`А.Шакиров` / `Асосий ижрочи:` / `Сув хўжалик вазирлиги`), и хвостом в одной строке с
человеком (`А. Арибжанов Асосий ижрочи:`). Разбор по абзацам пропустил бы вторую форму —
а это половина случаев.
"""


def split_responsible(value: str) -> tuple[str, str | None]:
    """Делит ячейку ответственного на нашего сотрудника и чужое ведомство.

    Возвращает пару: кто у нас, и головное ведомство, если оно названо. Ведомство есть в
    55 строках из 165, и именно по нему собирается ответ на вопрос «что сорвётся не по
    нашей вине».
    """
    text = normalize_spaces(value)
    lowered = text.lower()
    at = lowered.find(LEAD_EXECUTOR_MARKER)
    if at < 0:
        return text, None

    ours = text[:at].strip(" :;,-")
    theirs = text[at + len(LEAD_EXECUTOR_MARKER) :].strip(" :;,-")
    return ours, theirs or None


