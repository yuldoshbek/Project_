# Пункт документа (банд)
# ---------------------------------------------------------------------------

_BAND_WORDS = frozenset({"илова", "модда", "банд", "банди", "боб"})
"""Слова, которые входят в обозначение пункта, а не начинают его содержание."""

_BAND_TOKEN = re.compile(
    r"""
    \(?                                  # «3-модда (13.2-банд)» — скобка вокруг части
    (?:
        \d+(?:[.,][\dа-яёқғҳўa-z]+)*     # 26.2, 7.а.2, 13.2, 7.б
        # Точка перед дефисом необязательна и встречается: «7.б.-банд», «7.в.-банд».
        # Без неё суффикс отваливался, и пунктом становилось «7.б» — то есть три
        # разных подпункта одного банда слипались в один ключ.
        (?:\s*\.?\s*-\s*(?:илова|модда|банд|банди|боб))?
      | (?:илова|модда|банд|банди|боб)   # «Илова 85-банд» — слово без числа впереди
    )
    \)?\.?
    """,
    re.IGNORECASE | re.VERBOSE,
)


def extract_band(content: str) -> str | None:
    """Достаёт обозначение пункта из начала текста поручения.

    В источнике пункт не отдельная колонка — он приписан к содержанию: «5.1-банд», «2-илова
    26.3-банд», «9.а-банд», «3-модда (13.2-банд)», «Илова 85-банд». Вместе с номером
    документа и сроком он образует ключ повтора, без которого еженедельный привоз задваивает
    реестр.

    Правило простое и потому предсказуемое: **берём ведущие обозначения и останавливаемся
    на первом настоящем слове.** Разбирать обозначение на составные части (приложение,
    статья, пункт, подпункт) не нужно — сравнивать его будут целиком, а разбор добавил бы
    решений там, где их не спрашивают.

    Пусто — законное состояние: одна строка из 165 пункта не имеет.
    """
    text = normalize_spaces(content)
    taken: list[str] = []
    position = 0

    while position < len(text):
        match = _BAND_TOKEN.match(text, position)
        if match is None:
            break
        token = match.group(0)
        # Слово, не входящее в обозначение, — это уже содержание поручения.
        bare = token.strip("().,- ").lower()
        if bare.isalpha() and bare not in _BAND_WORDS:
            break
        taken.append(token)
        position = match.end()
        while position < len(text) and text[position] == " ":
            position += 1

        lowered = token.lower()
        if "банд" in lowered:
            # «Банд» закрывает обозначение. Без этого «4-илова 11.1-банд 2024 йил…»
            # утащило бы в пункт год из содержания — в данных таких строк три.
            break
        if any(character.isalpha() for character in "".join(taken[:-1])) and not any(
            character.isalpha() for character in token
        ):
            # Голое число после обозначения со словом — уже содержание: «2-илова 12.3
            # “Ўзбеккосмос”…» против «2-илова 12.3».
            break

    band = normalize_spaces(" ".join(taken)).rstrip(".")
    if not band or not any(character.isdigit() for character in band):
        # Обозначение без единой цифры — это не пункт, а начало предложения.
        return None
    return band[:BAND_MAX_LENGTH]


def band_sort_key(band: str | None) -> str:
    """Приводит пункт к виду, который сортируется по-человечески.

    По самому пункту сортировка врёт: «2.10» встаёт перед «2.9», потому что сравнение
    строковое. Карточка документа показала бы пункты не по порядку — а её открывают,
    чтобы увидеть картину по документу целиком.

    Числа дополняются нулями до шести знаков, буквы остаются как есть. Шести хватает с
    запасом: самый большой номер в данных — 85.
    """
    if band is None:
        return ""
    return re.sub(r"\d+", lambda match: match.group(0).rjust(6, "0"), band.lower())


