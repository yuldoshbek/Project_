"""«Ижро»: поручения вышестоящих органов. Словарь понятий.

Реестр заведён [ADR-0025](../../../docs/adr/ADR-0025-ijro-standalone-register.md) по
настоящим данным заказчика — трём годовым контрольным таблицам и разбору проблемных
поручений. Каждое решение в этом файле опирается на счёт, а не на предположение, и счёт
назван рядом.

Здесь только понятия: наборы значений и границы. Разбор `.docx`, восстановление года,
извлечение пункта и сведение написаний ФИО — соседний тикет; смешать их означало бы
получить файл, который нельзя прочитать за один присест.
"""

from __future__ import annotations

from enum import StrEnum

CODE_MAX_LENGTH = 20
"""Длина человекочитаемого номера: `IJR-2026-001` и запас на четырёхзначный счёт."""

BAND_MAX_LENGTH = 60
"""Длина пункта. Самый длинный в данных — «2-илова 26.3-банд», 17 знаков; запас втрое."""

RESPONSIBLE_RAW_MAX_LENGTH = 400
"""Строка ответственного как в источнике, вместе с хвостом «Асосий ижрочи: ведомство»."""


class IjroSource(StrEnum):
    """Откуда пришло поручение.

    Три таблицы с одинаковыми семью колонками — это не три сущности, а поле
    ([ADR-0025](../../../docs/adr/ADR-0025-ijro-standalone-register.md)). Единственное,
    что ADR-0023 угадал вслепую, и данные это подтвердили.

    Что именно означает «АПП» в названии третьего файла — **Q33**, вопрос заказчику.
    Ошибка в значении переносится миграцией, но портит аналитику по источникам, поэтому
    до ответа значения именуются по содержимому заголовка, а не по имени файла.
    """

    PA = "pa"
    """Фармойиш и резолюции руководителя Администрации Президента. 11 строк из 165."""

    VM = "vm"
    """Постановления Кабинета Министров (ВМҚ). 39 строк."""

    LEGAL = "legal"
    """Законодательные акты: фармон (ПФ), қарор (ПҚ), қонун (ЎРҚ), баён. 115 строк."""


class DocumentKind(StrEnum):
    """Вид документа вышестоящего органа.

    Значения — как в источнике, узбекской кириллицей в латинской записи: переводить их
    некуда. `OTHER` не запасной вариант «на всякий случай», а необходимость: 12 ячеек из
    165 не содержат узнаваемого префикса вовсе — `02-1671xdfu`, `78`, `19-2632`. Белый
    список видов потерял бы 8 % реестра.
    """

    FARMON = "farmon"
    """Указ Президента, ПФ."""

    QAROR = "qaror"
    """Постановление, ПҚ или ВМҚ."""

    QONUN = "qonun"
    """Закон, ЎРҚ."""

    BAYON = "bayon"
    """Протокол, баён."""

    TOPSHIRIQ = "topshiriq"
    """Поручение письмом."""

    OTHER = "other"
    """Номер без узнаваемого вида. Строка сохраняется как есть в `title_raw`."""


class IjroState(StrEnum):
    """Состояние исполнения поручения — то, ради чего система и заводится.

    В источнике графа «Ижро ҳолати» **пуста в 162 строках из 165**: он присылает план, а
    не состояние. Что сделано, что отправлено, что провисло — сегодня живёт только в
    голове помощника. Не заполнять эту графу значит показывать то же, что видно в Word.

    «Просрочено» здесь отсутствует намеренно: это вычисляемый признак, а не состояние
    (инвариант 1 `CLAUDE.md`, [ADR-0004](../../../docs/adr/ADR-0004-overdue-is-computed.md)).
    Записав его сюда, мы потеряли бы исходное состояние — а именно оно отвечает на
    вопрос «что с этим делать».
    """

    NOT_STARTED = "not_started"
    IN_PROGRESS = "in_progress"

    BLOCKED_BY_LEAD = "blocked_by_lead"
    """Головной исполнитель — чужое ведомство — не начал.

    Отдельное состояние, а не пометка в тексте: таких поручений 55 из 165, и вопрос
    руководителя «что сорвётся» почти целиком про них. Пометкой на это не ответить
    запросом.
    """

    SUBMITTED = "submitted"
    """Материал отправлен в `ijro.gov.uz`, ответа ещё нет."""

    DONE = "done"
    REMOVED_FROM_CONTROL = "removed_from_control"
    """«НАЗОРАТДАН ЕЧИЛДИ» — снято с контроля. Источник изредка это всё же присылает."""


TERMINAL_STATES = frozenset({IjroState.DONE, IjroState.REMOVED_FROM_CONTROL})
"""Состояния, после которых поручение не горит и в просрочку не попадает."""


class DuePrecision(StrEnum):
    """Насколько точен срок.

    **56 поручений из 165 стоят одной датой — 25 декабря.** Заказчик прочёл её так:
    «думаю, до конца года» (**Q31**). Слово «думаю» — это степень уверенности, и она
    сохраняется: прочтение принадлежит заказчику, а не выдавшему органу.

    Дата остаётся в `due_on` как есть — по ней сверяются с источником, — но смысл у неё
    другой, и расчёты обязаны его учитывать: такое поручение не горит за три дня до
    25 декабря и стоит отдельной полосой, а не столбцом того дня. Показать его обрывом
    значило бы соврать убедительно.

    Правило назначения живёт в настройках, а не в коде: следующий ответ заказчика про
    25 октября не должен становиться правкой кода.
    """

    EXACT = "exact"
    END_OF_YEAR = "end_of_year"


class DueYearSource(StrEnum):
    """Откуда взялся год: в источнике его нет.

    Срок записан как «25 декабрь» — без года. Год берётся из заголовка таблицы, а месяц
    **из самой ячейки**, а не из строки-разделителя: пять строк из 165 идут под чужим
    разделителем («25 август» под «СЕНТЯБРЬ»), и это перенесённые просрочки — самые
    ценные строки в таблице. Правило «месяц из разделителя» стёрло бы им срок.

    Признак хранится у каждой записи, потому что через месяц никто не вспомнит, что
    именно система решила за человека.
    """

    FROM_HEADER = "from_header"
    """Год взят из заголовка таблицы — обычный случай."""

    FROM_BLOCK = "from_block"
    """Месяц срока раньше месяца блока: перенесённая просрочка, год тот же."""

    MANUAL = "manual"
    """Год проставил человек: разбор не справился, и это видно в карточке."""


class ImportState(StrEnum):
    """Что с партией привоза.

    Предпросмотр — фаза, а не режим: разбор держится в базе, а не в памяти процесса,
    поэтому помощник может уйти, вернуться и показать разбор руководителю до того, как
    в реестр попадёт хоть одна строка.
    """

    PREVIEW = "preview"
    APPLIED = "applied"
    DISCARDED = "discarded"


class AliasSource(StrEnum):
    """Откуда взялось сопоставление написания с человеком или ведомством.

    Различать нужно потому, что доверие к ним разное. Автоматическое сведение безопасно
    ровно там, где отличие механическое: лишние пробелы, `И.Фамилия` вместо `И. Фамилия`,
    латинская `X` вместо кириллической `Х`. Всё остальное подтверждает человек — из-за
    одной строки в данных: `Ш. Арибжанов` при существующем `А. Арибжанове`. Другой
    инициал, другой человек, а любое правило склейки по фамилии соединит их молча.
    """

    AUTO = "auto"
    MANUAL = "manual"
