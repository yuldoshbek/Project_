"""Люди в системе: два разных понятия, которые нельзя смешивать.

**Пользователь** — тот, кто входит в ORBITA. Их двое: помощник заместителя директора и
сам заместитель ([ADR-0011](../../../docs/adr/ADR-0011-two-user-scope.md)).

**Сотрудник** — тот, на кого записана работа: куратор проекта, исполнитель задачи,
участник встречи. Таких десятки, и в систему они не входят.

Смешать их — значит завести сорок учётных записей, которыми никто не воспользуется.
Система при этом станет выглядеть многопользовательской, не будучи такой: появятся права,
которые никто не проверяет, и уведомления, которые некому читать.

Связь между понятиями односторонняя и необязательная: у пользователя может быть ссылка на
запись сотрудника (помощник и руководитель — тоже сотрудники агентства), у сотрудника
ссылки на пользователя нет.
"""

from __future__ import annotations

from enum import StrEnum


class Role(StrEnum):
    """Роль пользователя системы.

    Ровно две. Разграничения по проектам нет — делить нечего (ADR-0011).
    """

    ASSISTANT = "assistant"
    """Личный помощник заместителя директора. Вносит все данные, полный доступ."""

    LEADER = "leader"
    """Заместитель директора. Чтение всего плюс одно действие с записью —
    решение по проекту в статусе «На контроле руководителя» (ORB-062)."""

    @property
    def can_write(self) -> bool:
        """Может ли роль изменять данные вообще.

        У руководителя есть единственное исключение — решение по проекту. Оно
        проверяется отдельно, а не этим признаком: исключение должно быть видно в коде
        явно, иначе однажды под него подведут и всё остальное.
        """
        return self is Role.ASSISTANT
