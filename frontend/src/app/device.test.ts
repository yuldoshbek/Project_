/**
 * Выбор устройства по ширине.
 *
 * Границы заданы устройствами заказчика, и проверяются именно они: 390 — iPhone, 1440 —
 * ноутбук, 2560 — монитор в кабинете. Число «подошло примерно» здесь означает нижнюю панель
 * навигации на большом мониторе или боковую полосу на телефоне — то есть неработающий
 * интерфейс на том устройстве, где его открывают чаще всего.
 */

import { describe, expect, it } from 'vitest';

import { deviceFor } from './device';

describe('раскладка выбирается по устройству, а не растягивается', () => {
  it('iPhone — телефон', () => {
    expect(deviceFor(390)).toBe('phone');
  });

  it('узкое окно на ноутбуке — всё ещё телефон: важна ширина, а не техника', () => {
    expect(deviceFor(600)).toBe('phone');
  });

  it('планшет и ноутбук — одна раскладка с боковой полосой', () => {
    expect(deviceFor(768)).toBe('laptop');
    expect(deviceFor(1440)).toBe('laptop');
  });

  it('монитор в кабинете — своя раскладка', () => {
    expect(deviceFor(2560)).toBe('monitor');
  });

  it('граница монитора не задевает ноутбук 1440', () => {
    expect(deviceFor(1799)).toBe('laptop');
    expect(deviceFor(1800)).toBe('monitor');
  });
});
