/**
 * Показ времени по часовому поясу агентства.
 *
 * Проверка написана вокруг одного случая: метки, у которых ташкентская дата и дата UTC
 * не совпадают. На них ломается самый естественный способ показать срок — срезать из
 * строки первые десять символов, — и ломается тихо: девять сроков из десяти он покажет
 * верно, а десятый сдвинет на сутки, и заметят это по сорванному сроку.
 */

import { describe, expect, it } from 'vitest';

import { formatDate, formatDateTime } from './time';

describe('время агентства', () => {
  it('показывает дату по Ташкенту, а не по UTC', () => {
    // 30 августа 21:00 UTC — это уже 31 августа 02:00 в Ташкенте.
    expect(formatDate('2026-08-30T21:00:00Z')).toBe('31.08.2026');
    expect(formatDate('2026-08-30T21:00:00Z').slice(0, 2)).not.toBe('30');
  });

  it('показывает время по Ташкенту', () => {
    expect(formatDateTime('2026-09-14T12:00:00Z')).toBe('14.09.2026, 17:00');
  });

  it('не зависит от часового пояса машины, а только от пояса агентства', () => {
    // Одна и та же метка в двух записях: со смещением и без. Разбор обязан дать одно.
    expect(formatDateTime('2026-09-14T12:00:00Z')).toBe(
      formatDateTime('2026-09-14T17:00:00+05:00'),
    );
  });

  it('отсутствующий срок показывается пустотой, а не словом', () => {
    expect(formatDate(null)).toBe('');
    expect(formatDate(undefined)).toBe('');
    expect(formatDate('')).toBe('');
  });

  it('непонятная метка тоже пустая: «Invalid Date» читается как поломка', () => {
    expect(formatDate('послезавтра')).toBe('');
    expect(formatDateTime('2026-13-45')).toBe('');
  });
});
