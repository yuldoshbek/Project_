/**
 * Режим работы: помощник или руководитель. Вместо сессии.
 *
 * Входа в системе нет (ADR-0026): пользователей двое, границы между ними нет, и экран
 * входа охранял не их друг от друга, а систему от внешнего мира. Этим занимается
 * периметр. Здесь остаётся одно — в каком качестве человек сейчас работает.
 *
 * Режим не даёт прав и не отнимает их. Он делает две вещи: подписывает изменения в
 * журнале и решает, показывать ли кнопки правки. Руководитель, открывший систему
 * посмотреть, не должен случайно что-то изменить — это защита от промаха, а не от
 * злоумышленника, и говорить о ней надо честно.
 *
 * Типы и контекст лежат отдельно от компонента намеренно: файл, экспортирующий и
 * компонент, и что-то ещё, ломает быстрое обновление при разработке — правка хука
 * перезагружает всё дерево вместо одного компонента.
 */

import { createContext } from 'react';

export type Mode = 'assistant' | 'leader';

export const MODES: readonly Mode[] = ['assistant', 'leader'];

/** Ключ хранения выбора на устройстве. Выбор личный: у каждого свой ноутбук. */
export const MODE_STORAGE_KEY = 'orbita.mode';

/** Умолчание в пользу помощника: данные вносит он, и ошибка в его сторону безопаснее. */
export const DEFAULT_MODE: Mode = 'assistant';

export interface ModeValue {
  mode: Mode;
  setMode: (next: Mode) => void;
}

export const ModeContext = createContext<ModeValue | null>(null);

export function isMode(value: unknown): value is Mode {
  return typeof value === 'string' && (MODES as readonly string[]).includes(value);
}
